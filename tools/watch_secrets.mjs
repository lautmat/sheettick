// Writes the two git-ignored files the Garmin watch app needs (see garmin/README.md):
//   apps-script/WatchSecret.js   the token the web app accepts (pushed to Apps Script by clasp)
//   garmin/secrets/Secrets.mc    the web app URL and the same token, compiled into the watch app
//
//   node tools/watch_secrets.mjs --url https://script.google.com/macros/s/<deployment id>/exec
//
// The token is made once and kept: running it again (for a new URL) reuses it. Delete WatchSecret.js to make a new
// one, then push the script and rebuild the watch app. The token is never printed.
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const scriptFile = join(root, 'apps-script', 'WatchSecret.js');
const watchFile = join(root, 'garmin', 'secrets', 'Secrets.mc');

const args = process.argv.slice(2);
const urlArg = args.indexOf('--url') >= 0 ? args[args.indexOf('--url') + 1] : undefined;

let token;
if (existsSync(scriptFile)) {
  token = /WATCH_TOKEN = '([A-Za-z0-9_-]+)'/.exec(readFileSync(scriptFile, 'utf8'))?.[1];
  if (!token) throw new Error(`${scriptFile} has no WATCH_TOKEN; delete it to make a new one`);
  console.log('Kept the token in apps-script/WatchSecret.js');
} else {
  token = randomBytes(24).toString('base64url');
  writeFileSync(
    scriptFile,
    '// Generated by tools/watch_secrets.mjs. Git-ignored; clasp pushes it. The token the watch endpoint accepts.\n' +
      `var WATCH_TOKEN = '${token}';\n`,
  );
  console.log('Made a new token in apps-script/WatchSecret.js (push the script, then rebuild the watch app)');
}

let url = urlArg;
if (!url && existsSync(watchFile)) url = /URL = "([^"]+)"/.exec(readFileSync(watchFile, 'utf8'))?.[1];
if (!url) {
  console.log('No --url given and no garmin/secrets/Secrets.mc yet: deploy the web app, then run again with --url.');
  process.exit(0);
}
if (!/^https:\/\/script\.google\.com\/macros\/s\/[A-Za-z0-9_-]+\/exec$/.test(url)) {
  throw new Error(`Not an Apps Script web app URL: ${url}`);
}
mkdirSync(dirname(watchFile), { recursive: true });
writeFileSync(
  watchFile,
  '// Generated by tools/watch_secrets.mjs. Git-ignored: never commit.\n' +
    'import Toybox.Lang;\n\n' +
    '(:background)\n' +
    'module Secrets {\n' +
    `    const URL = "${url}";\n` +
    `    const TOKEN = "${token}";\n` +
    '}\n',
);
console.log('Wrote garmin/secrets/Secrets.mc');
